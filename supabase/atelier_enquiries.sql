-- Atelier Enquiries Table for Artace Studio
-- Run this in Supabase SQL Editor
--
-- Captures interest in a one-of-one original: either to acquire an available
-- piece, or to commission a similar work / register interest in a sold piece.
-- Deliberately lighter than photography_offers: no shipping address, because
-- an Atelier enquiry is a conversation starter, not a committed order.

CREATE TABLE IF NOT EXISTS atelier_enquiries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  enquiry_id TEXT UNIQUE NOT NULL,
  product_id TEXT NOT NULL,
  product_name TEXT NOT NULL,
  product_slug TEXT,
  -- 'acquire' when the piece was available at submit time, 'commission' when
  -- the visitor was told it had already been acquired.
  intent TEXT NOT NULL DEFAULT 'acquire',
  name TEXT NOT NULL,
  email TEXT NOT NULL,
  phone TEXT,
  message TEXT,
  user_agent TEXT,
  ip_address TEXT,
  created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
  updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Enable RLS (recommended)
ALTER TABLE atelier_enquiries ENABLE ROW LEVEL SECURITY;

-- Inserts go through the server route using the service-role key, which bypasses
-- RLS. This anon policy is a safety net only; drop it if you prefer strict
-- service-role-only writes.
CREATE POLICY "Allow insert for atelier enquiries" ON atelier_enquiries
  FOR INSERT
  WITH CHECK (true);

-- Reads are restricted to authenticated (admin) users.
CREATE POLICY "Allow select for authenticated users" ON atelier_enquiries
  FOR SELECT
  USING (auth.role() = 'authenticated');

-- Create indexes for faster lookups
CREATE INDEX IF NOT EXISTS idx_atelier_enquiries_enquiry_id ON atelier_enquiries (enquiry_id);
CREATE INDEX IF NOT EXISTS idx_atelier_enquiries_email ON atelier_enquiries (email);
CREATE INDEX IF NOT EXISTS idx_atelier_enquiries_product_id ON atelier_enquiries (product_id);
CREATE INDEX IF NOT EXISTS idx_atelier_enquiries_created_at ON atelier_enquiries (created_at DESC);
